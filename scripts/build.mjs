// Build: validates countries/ and translations/ (names from craftsmith/regions) and writes
//   src/data/<cc>.json          compiled rules (read by the PHP runtime)
//   js/data/<cc>.js, index.js   the same rules as ES modules (JS runtime)
//   json/<cc>/<year>.json, json/index.json   precomputed years (FILE_YEARS)
//   tests/fixtures/rules/<cc>.json   compiled test fixtures
// Exits with 1 and lists every problem when the data is invalid.

import { mkdirSync, rmSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import {
  checkTranslationIds,
  countryDirs,
  FILE_YEARS,
  FIXTURE_REGIONS,
  loadCountry,
  ROOT,
  TRANSLATIONS,
  validators,
} from './lib/data.mjs';
import { buildYear, encode, FORMAT } from '../js/engine.js';

const problems = [...TRANSLATIONS.errors];
const compile = (dir, options = {}) => {
  const out = [];
  for (const country of countryDirs(dir)) {
    const { rules, errors } = loadCountry(country, options);
    problems.push(...errors);
    if (rules) out.push(rules);
  }
  return out;
};

const countries = compile(join(ROOT, 'countries'));
const fixtures = compile(join(ROOT, 'tests/fixtures/data'), { regions: FIXTURE_REGIONS, translations: {} });
problems.push(...loadCountry(join(ROOT, 'countries/_template'), { expectCode: false, regions: FIXTURE_REGIONS, translations: {} }).errors);
problems.push(...checkTranslationIds(TRANSLATIONS.translations, countries));

if (problems.length > 0) {
  console.error(`Invalid data (${problems.length}):\n- ${problems.join('\n- ')}`);
  process.exit(1);
}

const write = (file, text) => {
  mkdirSync(join(file, '..'), { recursive: true });
  writeFileSync(file, text);
};

for (const dir of ['src/data', 'json', 'js/data', 'tests/fixtures/rules']) {
  rmSync(join(ROOT, dir), { recursive: true, force: true });
}

for (const rules of fixtures) {
  write(join(ROOT, 'tests/fixtures/rules', `${rules.code.toLowerCase()}.json`), encode(rules));
}

const header = '// Generated by scripts/build.mjs from countries/. Do not edit.\n';
for (const rules of countries) {
  const cc = rules.code.toLowerCase();
  write(join(ROOT, 'src/data', `${cc}.json`), encode(rules));
  write(join(ROOT, 'js/data', `${cc}.js`), `${header}export default ${JSON.stringify(rules, null, 2)};\n`);
}
write(
  join(ROOT, 'js/data/index.js'),
  header +
    countries.map((r) => `import ${r.code.toLowerCase()} from './${r.code.toLowerCase()}.js';\n`).join('') +
    `\nexport default { ${countries.map((r) => `${r.code}: ${r.code.toLowerCase()}`).join(', ')} };\n`,
);

let files = 0;
for (const rules of countries) {
  for (let y = FILE_YEARS.from; y <= FILE_YEARS.to; y += 1) {
    const doc = buildYear(rules, y);
    if (!validators.year(doc)) throw new Error(`${rules.code} ${y}: output does not match year.schema.json`);
    write(join(ROOT, 'json', rules.code.toLowerCase(), `${y}.json`), encode(doc));
    files += 1;
  }
}
const index = {
  format: FORMAT,
  years: FILE_YEARS,
  countries: countries.map((r) => ({
    code: r.code,
    names: r.names,
    languages: r.languages,
    regions: r.regions.map((g) => ({ code: g.code, names: g.names })),
  })),
};
if (!validators.index(index)) throw new Error('index.json does not match index.schema.json');
write(join(ROOT, 'json/index.json'), encode(index));

console.log(`Built ${countries.length} countries (${countries.map((r) => r.code).join(', ')}), ${files} year files ${FILE_YEARS.from}–${FILE_YEARS.to}, ${fixtures.length} fixtures.`);
