// Build: validates data/ and writes
//   dist/rules/<cc>.json      compiled rules (read by the PHP runtime)
//   js/data/<cc>.js, index.js the same rules as ES modules (JS runtime)
//   dist/json/<cc>/<year>.json, dist/json/index.json   precomputed years
//   tests/fixtures/rules/<cc>.json  compiled test fixtures
// Exits with 1 and lists every problem when the data is invalid.

import { mkdirSync, rmSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { countryDirs, loadCountry, ROOT, YEARS, validators } from './lib/data.mjs';
import { buildYear, encode, FORMAT } from '../js/engine.js';

const problems = [];
const compile = (dataDir) => {
  const out = [];
  for (const dir of countryDirs(dataDir)) {
    const { rules, errors } = loadCountry(dir);
    problems.push(...errors);
    if (rules) out.push(rules);
  }
  return out;
};

const countries = compile(join(ROOT, 'data'));
const fixtures = compile(join(ROOT, 'tests/fixtures/data'));
problems.push(...loadCountry(join(ROOT, 'data/_template'), { expectCode: false }).errors);

if (problems.length > 0) {
  console.error(`Invalid data (${problems.length}):\n- ${problems.join('\n- ')}`);
  process.exit(1);
}

const write = (file, text) => {
  mkdirSync(join(file, '..'), { recursive: true });
  writeFileSync(file, text);
};

for (const dir of ['dist/rules', 'dist/json', 'js/data', 'tests/fixtures/rules', 'tests/fixtures/json']) {
  rmSync(join(ROOT, dir), { recursive: true, force: true });
}

for (const rules of fixtures) {
  const cc = rules.code.toLowerCase();
  write(join(ROOT, 'tests/fixtures/rules', `${cc}.json`), encode(rules));
  for (let y = YEARS.from; y <= YEARS.to; y += 1) {
    write(join(ROOT, 'tests/fixtures/json', cc, `${y}.json`), encode(buildYear(rules, y)));
  }
}

const header = '// Generated by scripts/build.mjs from data/. Do not edit.\n';
for (const rules of countries) {
  const cc = rules.code.toLowerCase();
  write(join(ROOT, 'dist/rules', `${cc}.json`), encode(rules));
  write(join(ROOT, 'js/data', `${cc}.js`), `${header}export default ${JSON.stringify(rules, null, 2)};\n`);
}
write(
  join(ROOT, 'js/data/index.js'),
  header +
    countries.map((r) => `import ${r.code.toLowerCase()} from './${r.code.toLowerCase()}.js';\n`).join('') +
    `\nexport default { ${countries.map((r) => `${r.code}: ${r.code.toLowerCase()}`).join(', ')} };\n`,
);

let files = 0;
for (const rules of countries) {
  for (let y = YEARS.from; y <= YEARS.to; y += 1) {
    const doc = buildYear(rules, y);
    if (!validators.year(doc)) throw new Error(`${rules.code} ${y}: output does not match year.schema.json`);
    write(join(ROOT, 'dist/json', rules.code.toLowerCase(), `${y}.json`), encode(doc));
    files += 1;
  }
}
const index = {
  format: FORMAT,
  years: YEARS,
  countries: countries.map((r) => ({
    code: r.code,
    names: r.names,
    languages: r.languages,
    regions: r.regions.map((g) => ({ code: g.code, names: g.names })),
  })),
};
if (!validators.index(index)) throw new Error('index.json does not match index.schema.json');
write(join(ROOT, 'dist/json/index.json'), encode(index));

console.log(`Built ${countries.length} countries (${countries.map((r) => r.code).join(', ')}), ${files} year files ${YEARS.from}–${YEARS.to}, ${fixtures.length} fixtures.`);
